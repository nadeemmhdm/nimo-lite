def _safe_calculate(text):
    import ast,math,operator
    binary={ast.Add:operator.add,ast.Sub:operator.sub,ast.Mult:operator.mul,ast.Div:operator.truediv,ast.FloorDiv:operator.floordiv,ast.Mod:operator.mod,ast.Pow:operator.pow};unary={ast.UAdd:operator.pos,ast.USub:operator.neg}
    def walk(node,depth=0):
        if depth>12:raise ValueError("Expression too complex")
        if isinstance(node,ast.Expression):return walk(node.body,depth+1)
        if isinstance(node,ast.Constant) and isinstance(node.value,(int,float)):return node.value
        if isinstance(node,ast.UnaryOp) and type(node.op) in unary:return unary[type(node.op)](walk(node.operand,depth+1))
        if isinstance(node,ast.BinOp) and type(node.op) in binary:
            a,b=walk(node.left,depth+1),walk(node.right,depth+1)
            if isinstance(node.op,ast.Pow) and abs(float(b))>12:raise ValueError("Exponent too large")
            value=binary[type(node.op)](a,b)
            if isinstance(value,complex) or not math.isfinite(float(value)) or abs(float(value))>1e100:raise ValueError("Result out of bounds")
            return value
        raise ValueError("Only arithmetic is allowed")
    return walk(ast.parse(text,mode="eval"))

